#pragma once

#include "regs.hpp"

#include <array>
#include <cstdint>

namespace riscv {

class InterpreterEngine; // forward decl for ExecutorFn

// Arch bound
using word_t   = std::uint32_t;
using RawInstr = std::uint32_t;

enum InstrKind : std::uint8_t;

// TODO: implement
struct DecodedInstr;

const std::size_t memory_size = 4 * 1024;

struct MachineState {
    std::array<uint32_t, 32> regs{};
    std::array<uint8_t, memory_size> mem{};
    word_t pc{};
};

// Interface bound

// TODO:  implement
struct StepResult;
struct RunResult;

// Signatures for functions generated
using DecoderFn  = DecodedInstr (*)(const RawInstr);
using ExecutorFn = void (*)(InterpreterEngine&, const DecodedInstr&);

// Dispatch tables are generated by DSL architecture encoding & semantics description

class InterpreterEngine {
public:
    // State operations
    [[nodiscard]] word_t read_pc() const;
    [[nodiscard]] word_t read_reg(RegIndex index) const;
    void write_reg(RegIndex index, word_t value);

    // Memory operations
    [[nodiscard]] word_t load_s8 (word_t address) const;
    [[nodiscard]] word_t load_s16(word_t address) const;
    [[nodiscard]] word_t load_u8 (word_t address) const;
    [[nodiscard]] word_t load_u16(word_t address) const;
    [[nodiscard]] word_t load_u32(word_t address) const;

    void store8(word_t address, word_t value);
    void store16(word_t address, word_t value);
    void store32(word_t address, word_t value);

    // Control and environment
    void set_next_pc(word_t address);
    void memory_fence(std::uint8_t predecessor,
                      std::uint8_t successor);
    void environment_call();
    void breakpoint();

    // Pure semantic calculations
    [[nodiscard]] static bool signed_less(word_t lhs, word_t rhs);
    [[nodiscard]] static bool unsigned_less(word_t lhs, word_t rhs);
    [[nodiscard]] static word_t word_from_bool(bool value);
    [[nodiscard]] static word_t shift_left(word_t value, word_t amount);
    [[nodiscard]] static word_t shift_right_logical(word_t value,
                                                    word_t amount);
    [[nodiscard]] static word_t shift_right_arithmetic(word_t value,
                                                       word_t amount);
    [[nodiscard]] static word_t clear_low_bit(word_t value);

    StepResult step();
    RunResult run();

private:
    MachineState state_;

    [[nodiscard]] RawInstr fetch() const;
    [[nodiscard]] DecodedInstr decode(RawInstr raw) const;
    void execute(const DecodedInstr& instruction);
};

} // namespace riscv